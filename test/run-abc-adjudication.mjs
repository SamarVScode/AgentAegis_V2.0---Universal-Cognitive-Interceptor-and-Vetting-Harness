const results = [];

for (const issue of issues) {
  console.log(`\nAsking Jev: ${issue.id}`);
  try {
    const res = await callJevSystemOne({
      state: stateContext,
      questions: {
        [issue.id]: {
          type: 'noul',
          instructions: issue.instructions,
          criteria: {
            true: issue.criteria_true,
            false: issue.criteria_false
          }
        }
      },
      timeoutMs: 15000,
      maxRetries: 2
    });

    const answer = res.answers?.[issue.id];
    const noul = answer?.noul ?? answer?.probability ?? null;
    const verdict = noul !== null ? (noul >= 0.5 ? 'TRUE' : 'FALSE') : 'unknown';
    console.log(`  noul=${noul}  verdict=${verdict}`);
    console.log(`  raw answer: ${JSON.stringify(answer)}`);
    results.push({ id: issue.id, noul, verdict, answer, usage: res.usage });
  } catch (err) {
    console.log(`  ERROR: ${err.message}`);
    results.push({ id: issue.id, error: err.message });
  }
}

const outPath = path.join(root, 'test', 'jev-abc-adjudication.json');
fs.writeFileSync(outPath, JSON.stringify(results, null, 2));
console.log('\nSaved to:', outPath);

